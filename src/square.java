public class square {
    static int sqrt(int n){
        return n*n;
    }

    static int sum(int n1, int n2){
        return n1 + n2;
    }

    public static void main(String[] args){
        System.out.println(sqrt(5));
        System.out.println(sqrt(67));


        System.out.println(sum(67, 69));
    }
}